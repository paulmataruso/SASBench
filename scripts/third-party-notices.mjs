#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md (and web/public/third-party-notices.txt, served by the UI) from
// the license files of every npm package that ships: server runtime dependencies, the packages
// bundled into the web UI, and build tools whose code ends up in the bundle. Run after changing
// dependencies; `--check` exits non-zero when the committed files are out of date.
//
//   npm run notices         # regenerate
//   npm run notices:check   # verify (CI)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const WEB = path.join(ROOT, 'web');
const OUT_MD = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');
const OUT_TXT = path.join(WEB, 'public', 'third-party-notices.txt');
const check = process.argv.includes('--check');

/** Production dependency tree of a package directory (paths of installed packages). */
function prodPackages(dir) {
  const out = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { cwd: dir, encoding: 'utf8' });
  return out.split('\n').map((l) => l.trim()).filter((l) => l && path.resolve(l) !== path.resolve(dir));
}

function pkgInfo(dir) {
  const pj = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const files = fs.readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)([.-].*)?$/i.test(f)).sort();
  // Vite's license file appends the licenses of its dev-server dependencies, none of which reach the
  // built bundle (only Vite's own preload helper does); keep Vite's own license.
  const texts = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').split(/^# Licenses of bundled dependencies/m)[0].trim());
  const repo = typeof pj.repository === 'string' ? pj.repository : pj.repository?.url;
  return {
    name: pj.name,
    version: pj.version,
    license: pj.license ?? (Array.isArray(pj.licenses) ? pj.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN'),
    homepage: pj.homepage ?? (repo ? repo.replace(/^git\+/, '').replace(/\.git$/, '') : null),
    texts,
  };
}

function collect(dirs) {
  const seen = new Map();
  for (const d of dirs) {
    const p = pkgInfo(d);
    seen.set(`${p.name}@${p.version}`, p);
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
const groups = [
  ['Server runtime (Node.js packages)', collect(prodPackages(ROOT))],
  ['Web UI (bundled into the browser application)', collect(prodPackages(WEB))],
  ['Build tools whose code is included in the web UI bundle', collect(['vite', 'tailwindcss'].map((n) => path.join(WEB, 'node_modules', n)))],
];

const L = [];
L.push(`# Third-party notices`, '');
L.push(`SASBench ${version} includes the third-party software and data listed below. Each component is`);
L.push(`licensed by its authors under the license shown; those licenses apply to the component, not to`);
L.push(`SASBench as a whole.`, '');
L.push(`This file is generated by \`scripts/third-party-notices.mjs\`.`, '');

L.push(`## Runtime included in the container image`, '');
L.push(`- **Node.js** (MIT, plus the licenses of the components it bundles). The full license text is in`);
L.push(`  \`/app/licenses/node-LICENSE\` inside the image and at https://github.com/nodejs/node/blob/main/LICENSE.`);
L.push(`- **OpenSSL** (Apache-2.0), https://www.openssl.org/source/license.html`);
L.push(`- **tini** (MIT), https://github.com/krallin/tini`);
L.push(`- **Alpine Linux base packages**, each under its own license (MIT, BSD, GPL-2.0 and others). The installed`);
L.push(`  packages with their versions and licenses are listed in \`/app/licenses/alpine-packages.txt\` inside the`);
L.push(`  image. Source code for every package is available from https://gitlab.alpinelinux.org/alpine/aports`);
L.push(`  and https://dl-cdn.alpinelinux.org/alpine/.`, '');

L.push(`## Data`, '');
L.push(`- **Natural Earth** vector map data (public domain), used for the built-in offline basemap.`);
L.push(`  Made with Natural Earth. Free vector and raster map data @ naturalearthdata.com.`);
L.push(`- **NTIA DPA definitions** (E-DPA and P-DPA KML files), U.S. National Telecommunications and Information`);
L.push(`  Administration. Works of the U.S. Government, not subject to copyright in the United States.`);
L.push(`- **USGS 3DEP** 1-arc-second elevation tiles, when fetched for the Category A HAAT check, and **NED**`);
L.push(`  GridFloat tiles from the WInnForum Common-Data repository when installed. Works of the U.S. Geological`);
L.push(`  Survey, public domain. Credit: U.S. Geological Survey, 3D Elevation Program.`);
L.push(`- **USGS The National Map** tiles, when selected as the map source or downloaded for offline use.`);
L.push(`  Works of the U.S. Geological Survey, public domain. Credit: USGS The National Map.`);
L.push(`- **OpenStreetMap** tiles, only when an operator selects them as the map source: map data`);
L.push(`  © OpenStreetMap contributors, available under the Open Database License (https://www.openstreetmap.org/copyright).`, '');

for (const [title, pkgs] of groups) {
  L.push(`## ${title}`, '');
  for (const p of pkgs) {
    L.push(`### ${p.name} ${p.version}`, '');
    L.push(`- License: ${p.license}`);
    if (p.homepage) L.push(`- Source: ${p.homepage}`);
    L.push('');
    if (p.texts.length) {
      for (const t of p.texts) L.push('```', t, '```', '');
    } else {
      L.push(`(The package ships no license file; its package.json declares ${p.license}.)`, '');
    }
  }
}

const md = L.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
if (check) {
  const stale = [OUT_MD, OUT_TXT].filter((f) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== md);
  if (stale.length) {
    console.error(`Out of date: ${stale.map((f) => path.relative(ROOT, f)).join(', ')}. Run npm run notices.`);
    process.exit(1);
  }
  console.log('Third-party notices are up to date.');
} else {
  fs.writeFileSync(OUT_MD, md);
  fs.mkdirSync(path.dirname(OUT_TXT), { recursive: true });
  fs.writeFileSync(OUT_TXT, md);
  const n = groups.reduce((a, [, p]) => a + p.length, 0);
  console.log(`Wrote ${path.relative(ROOT, OUT_MD)} and ${path.relative(ROOT, OUT_TXT)} (${n} packages).`);
}
